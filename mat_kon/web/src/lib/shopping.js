// שם מצרך לרשימת הקניות: בלי כמות, יחידה, גודל והערות ("4 ביצים L" → "ביצים", "2 כוסות קמח, מנופה" → "קמח")

const UNITS = [
  'כוסות', 'כוס', 'כפות', 'כף', 'כפיות', 'כפית', 'גרם', "ג'", 'ג׳', 'ג', 'קילוגרם', 'קילו', 'ק"ג', 'ק״ג', 'קג',
  'מיליליטר', 'מ"ל', 'מ״ל', 'מל', 'ליטר', "ל'", 'ל׳', 'חבילות', 'חבילת', 'חבילה', 'קופסאות', 'קופסות', 'קופסת', 'קופסה',
  'שקיות', 'שקית', 'יחידות', 'יחידה', 'פרוסות', 'פרוסה', 'שיני', 'שן', 'צרור', 'צרורות', 'קורט', 'קמצוץ', 'חופן', 'חופנים',
  'מגש', 'בקבוק', 'פחית', 'פחיות', 'ענפי', 'ענף', 'גביע', 'גביעים', 'מקלות', 'מקל', 'ראש', 'ראשי', 'אריזה', 'אריזת',
  'tbsp', 'tsp', 'cups?', 'g', 'kg', 'ml',
];
const AMOUNT_WORDS = ['חצי', 'רבע', 'שליש', 'שלושת רבעי', 'אחד', 'אחת', 'שני', 'שתי', 'שניים', 'שתיים', 'שלוש', 'שלושה', 'ארבע', 'ארבעה', 'חמש', 'חמישה', 'כמה'];
const SIZES = /\s+(גדול|גדולה|גדולים|גדולות|בינוני|בינונית|בינוניים|בינוניות|קטן|קטנה|קטנים|קטנות|[LMS]|XL)$/;

// אופן הכנה – לא חלק מהמוצר ("בצל קצוץ", "עגבניות בשלות מרוסקות"). "טחון" ו"קלוי" נשארים (בשר טחון, שקדים קלויים)
const PREP = /\s+(קצו[ץצ]\S*|חתו[ךכ]\S*|פרוס(?:ה|ים|ות)?|מגורר\S*|כתו[שש]\S*|מרוסק\S*|מבושל\S*|מומס\S*|מקולף\S*|מקולפ\S*|שטו[ףפ]\S*|מנופה|רכה?|בשל(?:ה|ים|ות)?|טר(?:י|ייה|יה|יים|יות))(\s.*)?$/;
const NUMBER = /^[\d½⅓⅔¼¾⅛.,/\s-–]+/;
const UNIT = new RegExp(`^(${UNITS.join('|')})(?=\\s|$)\\s*(של\\s+)?`, 'i');
const WORD = new RegExp(`^(${AMOUNT_WORDS.join('|')})(?=\\s|$)\\s*`);

export function shoppingName(line) {
  const original = String(line || '').trim();
  let s = original
    .replace(/\([^)]*\)/g, ' ') // הערות בסוגריים
    .split(/[,;–]| - /)[0] // מה שאחרי פסיק: "קצוץ דק", "לקישוט"
    .replace(/\s+/g, ' ')
    .trim();
  for (let i = 0; i < 4; i += 1) {
    const before = s;
    s = s.replace(NUMBER, '').replace(WORD, '').replace(UNIT, '').trim();
    if (s === before) break;
  }
  s = s.replace(PREP, '').replace(SIZES, '').replace(/\s*(לפי הטעם|לקישוט|להגשה)$/, '').trim();
  return s || original;
}
