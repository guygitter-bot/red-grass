export function pick(v, type) {
  return v && typeof v === 'object' && !Array.isArray(v) && ('classical' in v || 'electric' in v) ? v[type] : v;
}

// בדיקת תקינות: כל חלק קיים לשתי הגיטרות (משמש את הבדיקות)
export function partExists(type, part) {
  return !!PART_NAMES[type][part];
}
