// ---------- שאלות ----------
const clean = (s) => (typeof s === 'string' ? s.trim() : '');

// משפט הכוונה: מחרוזת או אובייקט כוונה ({ text })
const intentionText = (i) => (typeof i === 'string' ? clean(i) : clean(i?.text));

// עד שלושה סמלים מהתגיות, להצמדה לשאלות
function symbols(entry) {
  const tags = Array.isArray(entry?.tags) ? entry.tags.map(clean).filter(Boolean) : [];
  return tags.slice(0, 3);
}
const list = (xs) => xs.map((x) => `«${x}»`).join(', ');

// כותרת החלום בתוך שאלה (אם יש)
const about = (entry) => (clean(entry?.title) ? `בחלום "${clean(entry.title)}"` : 'בחלום');

function hdQuestions(entry, settings, intention) {
  const t = hdType(settings?.hd?.type);
  const a = hdAuth(settings?.hd?.authority);
  const syms = symbols(entry);
  const qs = [];
  qs.push({
    q: `${about(entry)}: מה מורגש בגוף ובלב ברגע החזק ביותר?`,
    hint: 'לא מה זה אומר – רק איך זה הרגיש.',
  });
  if (t) {
    qs.push({
      q: `האסטרטגיה של הסוג (${t.name}) היא ${t.strategy}. האם בחלום פעלו כך, או הפוך?`,
      hint: 'אפשר לשים לב מה קרה כשפעלו בדרך אחת או בדרך אחרת.',
    });
    qs.push({
      q: `יש בחלום משהו שמזכיר ${t.notSelf}? איפה זה הופיע?`,
      hint: `בשיטה הזאת זה איתות שמשהו לא מתאים. אפשר לשאול: מה בחיים הערים מרגיש ככה?`,
    });
    qs.push({
      q: `יש בחלום רגע של ${t.sig}? מה קרה סביבו?`,
      hint: 'זו התחושה שבשיטה מתארת התאמה.',
    });
  } else {
    qs.push({
      q: 'האם בחלום הגבת למה שקרה, או יזמת? איך זה הרגיש?',
      hint: 'אפשר לבחור סוג בהגדרות ולקבל שאלות מותאמות.',
    });
    qs.push({
      q: 'יש בחלום רגע של תסכול, כעס, מרירות או אכזבה? איפה זה הופיע?',
      hint: 'בשיטה הזאת אלה איתותים שמשהו לא מתאים.',
    });
    qs.push({
      q: 'יש בחלום רגע של סיפוק, הצלחה, שלווה או הפתעה טובה?',
      hint: 'בשיטה הזאת אלה סימנים להתאמה.',
    });
  }
  if (a) {
    qs.push({
      q: `התוקף שלך הוא ${a.name}: ${a.meaning}. מה החלום משאיר להחליט, ואיך מחכים לתחושה הזאת?`,
      hint: a.hint,
    });
  } else {
    qs.push({
      q: 'איך מקבלים בדרך כלל החלטות: מהגוף, מהרגש, מאינטואיציה או בשיחה? איך זה קשור לחלום?',
      hint: 'אפשר לבחור תוקף בהגדרות.',
    });
  }
  if (syms.length) {
    qs.push({
      q: `מה ${list(syms)} מעוררים אצלך כרגע, בחיים הערים?`,
      hint: 'לא חייבים לפרש – מספיק לשים לב.',
    });
  }
  const it = intentionText(intention);
  if (it) qs.push({ q: `הכוונה שלך הייתה: "${it}". מה בחלום נוגע בה, ומה לא?`, hint: 'גם "שום דבר" זו תשובה.' });
  qs.push({
    q: 'מה אפשר לבדוק בימים הקרובים, בלי למהר להחליט?',
    hint: 'חלום הוא לא הוראה. מחליטים בעירות.',
  });
  return qs;
}

