  const it = intentionText(intention);
  if (it) qs.push({ q: `הכוונה הייתה: "${it}". איזה חלק מהחלום יכול ללמד עליה, ואיזה פשוט רעש?`, hint: 'לא כל חלום צריך פירוש.' });
