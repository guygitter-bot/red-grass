// מזהה קבוע לכל שיר (לפי השם והזמר, כדי שהמטמון לא יתבלבל כשמוסיפים שירים)
function songId(title, artist) {
  let h = 2166136261;
  for (const ch of `${title}|${artist}`) {
    h ^= ch.codePointAt(0);
    h = Math.imul(h, 16777619) >>> 0;
  }
  return `s${h.toString(36)}`;
}

export const SONGS = [];
for (const [lang, decades] of Object.entries(RAW)) {
  for (const [decade, list] of Object.entries(decades)) {
    for (const line of list) {
      const [title, artist] = line.split('|');
      SONGS.push({ id: songId(title, artist), title, artist, lang, decade });
    }
  }
}
export const SONG_BY_ID = new Map(SONGS.map((s) => [s.id, s]));
